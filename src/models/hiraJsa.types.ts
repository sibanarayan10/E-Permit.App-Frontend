/**
 * HIRA JSA (Hazard Identification & Risk Assessment) Types
 * 
 * These types match the backend Mongoose schema exactly.
 */

// ============================================
//   CONSTANTS
// ============================================

export const RISK_LEVELS = {
    LOW: "Low",
    MEDIUM: "Medium",
    HIGH: "High",
    EXTREME: "Extreme"
} as const;

export type RiskLevel = typeof RISK_LEVELS[keyof typeof RISK_LEVELS];

export const OPPORTUNITY_OPTIONS = [
    "Elimination",
    "Substitution",
    "Engineering Control",
    "Administrative Control",
    "PPEs"
] as const;

export type OpportunityOption = typeof OPPORTUNITY_OPTIONS[number];

export const HIRA_STATUS = {
    DRAFT: "Draft",
    SUBMITTED: "Submitted",
    LOCKED: "Locked"
} as const;

export type HiraStatus = typeof HIRA_STATUS[keyof typeof HIRA_STATUS];

// ============================================
//   HIRA ROW INTERFACE
// ============================================

export interface HiraRow {
    _id?: string;

    // Serial number - auto-generated by backend
    serialNo: number;

    // Task / Activity (required)
    taskActivity: string;

    // Hazards - array of strings
    hazards: string[];

    // Risks - array of strings
    risks: string[];

    // Existing Control Measures (ECM)
    existingControlMeasures: string[];

    // Likelihood (1-5) - required
    likelihood: number;

    // Severity (1-5) - required
    severity: number;

    // Risk Score - AUTO CALCULATED by backend (L × S)
    riskScore?: number;

    // Risk Level - AUTO CALCULATED by backend
    riskLevel?: RiskLevel;

    // Opportunity (dropdown)
    opportunity?: OpportunityOption | "";

    // Additional Control Measures (ACM)
    additionalControlMeasures: string[];

    // Residual Likelihood (1-5)
    residualLikelihood?: number | null;

    // Residual Severity (1-5)
    residualSeverity?: number | null;

    // Residual Risk Score - AUTO CALCULATED by backend
    residualRiskScore?: number;

    // Residual Risk Level - AUTO CALCULATED by backend
    residualRiskLevel?: RiskLevel | "";

    // Responsibility
    responsibility?: string;
}

// ============================================
//   JOB HEADER INTERFACE (MANDATORY FIELDS ONLY)
// ============================================

export interface HiraJobHeader {
    area: string;
    jobType: string;
    jobDetails: string;
    preparedBy: string;
}

// ============================================
//   AUDIT TRAIL INTERFACE
// ============================================

export interface HiraAuditEntry {
    action: "created" | "updated" | "submitted" | "locked" | "row_added" | "row_updated" | "row_deleted";
    performedBy?: {
        _id: string;
        name: string;
        email: string;
    };
    performedAt: string;
    changes?: Record<string, unknown>;
    previousValues?: Record<string, unknown>;
}

// ============================================
//   VALIDATION WARNING INTERFACE
// ============================================

export interface HiraValidationWarning {
    rowIndex: number;
    message: string;
    type: "acm_required" | "high_residual_risk" | "extreme_risk";
}

// ============================================
//   RISK REDUCTION SUMMARY (VIRTUAL)
// ============================================

export interface RiskReductionSummary {
    totalInitialScore: number;
    totalResidualScore: number;
    reduction: number;
    reductionPercentage: number;
    rowsAnalyzed: number;
    rowsWithResidual: number;
}

// ============================================
//   MAIN HIRA JSA INTERFACE
// ============================================

export interface HiraJsa {
    _id: string;

    // Auto-generated identifier
    hiraNumber: string;

    // Job Header (mandatory fields only)
    jobHeader: HiraJobHeader;

    // HIRA Table Rows
    rows: HiraRow[];

    // Status
    status: HiraStatus;

    // Created by
    createdBy: {
        _id: string;
        name: string;
        email: string;
    };

    // Locking
    isLocked: boolean;

    // Is this the default HIRA template for permits
    isDefault?: boolean;

    lockedAt?: string;
    lockedBy?: {
        _id: string;
        name: string;
        email: string;
    };

    // Audit Trail
    auditTrail: HiraAuditEntry[];

    // Template Reference
    clonedFrom?: {
        _id: string;
        hiraNumber: string;
    };

    // Validation Warnings
    validationWarnings: HiraValidationWarning[];

    // Virtual: Risk Reduction Summary
    riskReductionSummary?: RiskReductionSummary;

    // Timestamps
    createdAt: string;
    updatedAt: string;
}

// ============================================
//   API REQUEST/RESPONSE TYPES
// ============================================

/**
 * Request body for creating a new HIRA
 */
export interface CreateHiraRequest {
    jobHeader: HiraJobHeader;
    rows: Omit<HiraRow, "_id" | "serialNo" | "riskScore" | "riskLevel" | "residualRiskScore" | "residualRiskLevel">[];
}

/**
 * Request body for updating a HIRA
 */
export interface UpdateHiraRequest {
    jobHeader?: Partial<HiraJobHeader>;
    rows?: Omit<HiraRow, "_id" | "serialNo" | "riskScore" | "riskLevel" | "residualRiskScore" | "residualRiskLevel">[];
}

/**
 * Request body for adding a row
 */
export interface AddHiraRowRequest {
    taskActivity: string;
    hazards?: string[];
    risks?: string[];
    existingControlMeasures?: string[];
    likelihood: number;
    severity: number;
    opportunity?: OpportunityOption | "";
    additionalControlMeasures?: string[];
    residualLikelihood?: number | null;
    residualSeverity?: number | null;
    responsibility?: string;
}

/**
 * ACM Validation Error
 */
export interface ACMValidationError {
    rowIndex: number;
    serialNo: number;
    riskLevel: RiskLevel;
    message: string;
}

/**
 * API Response for HIRA operations
 */
export interface HiraApiResponse<T = HiraJsa> {
    success: boolean;
    message: string;
    data: T;
    warnings?: HiraValidationWarning[];
    acmValidation?: {
        hasErrors: boolean;
        errors: ACMValidationError[];
    } | null;
}

/**
 * API Response for HIRA list
 */
export interface HiraListResponse {
    success: boolean;
    message: string;
    data: {
        hiras: HiraJsa[];
        pagination: {
            current: number;
            total: number;
            count: number;
            totalRecords: number;
            hasNext: boolean;
            hasPrev: boolean;
        };
    };
}

