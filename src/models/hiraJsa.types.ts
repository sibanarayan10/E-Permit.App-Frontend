// ============================================
//   HELPER FUNCTIONS (Frontend Preview Only)
// ============================================

/**
 * Calculate risk score (for frontend preview only)
 * Backend is the source of truth and will override this
 */
export const calculateRiskScorePreview = (likelihood: number, severity: number): number => {
    return (likelihood || 0) * (severity || 0);
};

/**
 * Get risk level (for frontend preview only)
 * Backend is the source of truth and will override this
 */
export const getRiskLevelPreview = (riskScore: number): RiskLevel => {
    if (riskScore >= 16) return RISK_LEVELS.EXTREME;
    if (riskScore >= 11) return RISK_LEVELS.HIGH;
    if (riskScore >= 6) return RISK_LEVELS.MEDIUM;
    return RISK_LEVELS.LOW;
};

/**
 * Get color for risk level
 */
export const getRiskLevelColor = (riskLevel?: RiskLevel | ""): string => {
    switch (riskLevel) {
        case RISK_LEVELS.LOW: return "#00B050";
        case RISK_LEVELS.MEDIUM: return "#FFC000";
        case RISK_LEVELS.HIGH: return "#FF8000";
        case RISK_LEVELS.EXTREME: return "#FF0000";
        default: return "#808080";
    }
};

/**
 * Get background color for risk level (lighter version)
 */
export const getRiskLevelBgColor = (riskLevel?: RiskLevel | ""): string => {
    switch (riskLevel) {
        case RISK_LEVELS.LOW: return "#E2F0D9";
        case RISK_LEVELS.MEDIUM: return "#FFF2CC";
        case RISK_LEVELS.HIGH: return "#FCE4D6";
        case RISK_LEVELS.EXTREME: return "#F8CBAD";
        default: return "#F2F2F2";
    }
};

/**
 * Check if ACM is required based on risk level
 */
export const isACMRequired = (riskLevel?: RiskLevel | ""): boolean => {
    return riskLevel === RISK_LEVELS.MEDIUM ||
        riskLevel === RISK_LEVELS.HIGH ||
        riskLevel === RISK_LEVELS.EXTREME;
};

